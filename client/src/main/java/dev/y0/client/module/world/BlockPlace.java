package dev.y0.client.module.world;

import dev.y0.client.event.EventHandler;
import dev.y0.client.event.events.EventTick;
import dev.y0.client.module.Category;
import dev.y0.client.module.Module;
import dev.y0.client.setting.NumberSetting;
import net.minecraft.item.BlockItem;
import net.minecraft.util.Hand;
import net.minecraft.util.hit.BlockHitResult;
import net.minecraft.util.hit.HitResult;

public class BlockPlace extends Module {
    private final NumberSetting delay = addSetting(new NumberSetting("Delay", "Ticks between placements", 0.0, 0.0, 4.0, 1.0));
    private int tickCounter;

    public BlockPlace() {
        super("BlockPlace", "Fast block placement with configurable delay", Category.WORLD);
    }

    @EventHandler
    public void onTick(EventTick event) {
        if (mc.player == null || mc.world == null || mc.interactionManager == null) return;

        tickCounter++;
        if (tickCounter < (int) delay.getValue()) return;
        tickCounter = 0;

        if (!(mc.player.getMainHandStack().getItem() instanceof BlockItem)) return;
        if (mc.crosshairTarget == null || mc.crosshairTarget.getType() != HitResult.Type.BLOCK) return;

        BlockHitResult hit = (BlockHitResult) mc.crosshairTarget;
        mc.interactionManager.interactBlock(mc.player, Hand.MAIN_HAND, hit);
        mc.player.swingHand(Hand.MAIN_HAND);
    }
}
